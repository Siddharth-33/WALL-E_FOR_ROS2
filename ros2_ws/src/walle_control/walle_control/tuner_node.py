#!/usr/bin/env python3
"""
tuner_node.py
=============
An interactive ROS2 node for tuning PID gains and switching modes
on the ESP32 — wirelessly, without reflashing.

WHAT THIS NODE DOES:
  - Creates a Service CLIENT for /set_pid_gains
  - Creates a Service CLIENT for /set_mode
  - Provides an interactive menu in the terminal
  - Lets you type new gains and send them to the robot instantly

WHY THIS IS POWERFUL:
  Traditional embedded workflow:
    Edit firmware code → Compile (2-5 min) → Flash to ESP32 → Test → Repeat
    Total per iteration: ~10 minutes

  With this node:
    Type new gains → Press Enter → Robot updates in <100ms → Test → Repeat
    Total per iteration: ~5 seconds

  For PID tuning where you might need 50+ iterations, this saves hours.

HOW TO RUN (in a separate terminal):
  ros2 run walle_control tuner_node
"""

import rclpy
from rclpy.node import Node

# ── Import service types (generated by rosidl from our .srv files) ────────────
# These give us the Request and Response classes for each service.
from walle_interfaces.srv import SetPidGains, SetMode


class TunerNode(Node):
    """
    Interactive PID tuner. Creates service clients and lets the user
    send gain updates and mode switches from the terminal.
    """

    def __init__(self):
        super().__init__('walle_tuner')

        # ── Create Service CLIENTS ─────────────────────────────────────────────
        # A service CLIENT sends requests to a service SERVER.
        # Our ESP32 runs the service SERVERS (it handles /set_pid_gains, /set_mode).
        # This node is the CLIENT — it sends requests and waits for responses.
        #
        # Think of it like a remote control:
        #   Client (this node) = you pressing buttons on the remote
        #   Server (ESP32)     = the device receiving the button presses
        #
        # Syntax: self.create_client(ServiceType, '/service_name')
        self.pid_client = self.create_client(SetPidGains, '/set_pid_gains')
        self.mode_client = self.create_client(SetMode, '/set_mode')

        self.get_logger().info('Wall-E Tuner Node started.')

    def wait_for_services(self, timeout_sec=5.0):
        """
        Wait until the ESP32's service servers are available.
        Returns True if both services are up, False if timeout.

        WHY WE WAIT:
        If you run this node before the ESP32 is connected, the services
        don't exist yet. We wait for them to appear before sending requests.
        """
        self.get_logger().info('Waiting for ESP32 services...')
        pid_ready = self.pid_client.wait_for_service(timeout_sec=timeout_sec)
        mode_ready = self.mode_client.wait_for_service(timeout_sec=timeout_sec)

        if not pid_ready or not mode_ready:
            self.get_logger().error(
                'Services not available! Is the ESP32 connected and micro-ROS agent running?'
            )
            return False

        self.get_logger().info('ESP32 services ready!')
        return True

    def set_pid_gains(self, controller: str, kp: float, ki: float, kd: float):
        """
        Send a PID gain update request to the ESP32.

        HOW SYNCHRONOUS SERVICE CALLS WORK:
        1. We create a Request object and fill its fields
        2. We send it to the server using call_async() — this is non-blocking
        3. We spin until the future completes (response arrives)
        4. We read the Response and print the result

        WHY call_async() instead of call()?
        call() would block the entire thread (including ROS2's event loop).
        call_async() sends the request and returns a "Future" — a promise
        that the response will arrive later. We then spin_until_future_complete()
        to wait for it without blocking the event loop.
        """
        # Step 1: Build the request
        # SetPidGains.Request() creates an empty request object
        # with all fields at their zero/default values
        request = SetPidGains.Request()
        request.controller = controller   # "balance" or "line"
        request.kp = float(kp)
        request.ki = float(ki)
        request.kd = float(kd)

        self.get_logger().info(
            f'Sending: {controller} PID → Kp={kp}, Ki={ki}, Kd={kd}'
        )

        # Step 2: Send the request asynchronously
        # future is like a "ticket" — when the response arrives, the future is "done"
        future = self.pid_client.call_async(request)

        # Step 3: Wait for the response (up to 5 seconds)
        # rclpy.spin_until_future_complete() keeps running the ROS2 event loop
        # (processing incoming messages, timers, etc.) until our future resolves.
        rclpy.spin_until_future_complete(self, future, timeout_sec=5.0)

        # Step 4: Read and display the response
        if future.done():
            response = future.result()
            if response.success:
                self.get_logger().info(f'SUCCESS: {response.message}')
            else:
                self.get_logger().error(f'FAILED: {response.message}')
        else:
            self.get_logger().error('TIMEOUT: No response from ESP32 within 5 seconds')

    def set_mode(self, mode: int):
        """Send a mode switch request to the ESP32."""
        request = SetMode.Request()
        request.mode = int(mode)

        mode_names = {0: 'IDLE', 1: 'BALANCE_ONLY', 2: 'LINE_FOLLOW', 3: 'BOTH'}
        self.get_logger().info(
            f'Switching to mode {mode} ({mode_names.get(mode, "UNKNOWN")})'
        )

        future = self.mode_client.call_async(request)
        rclpy.spin_until_future_complete(self, future, timeout_sec=5.0)

        if future.done():
            response = future.result()
            status = '[SUCCESS]' if response.success else '[FAILED]'
            self.get_logger().info(f'{status} Mode is now: {response.current_mode}')
        else:
            self.get_logger().error('TIMEOUT: No response from ESP32')

    def interactive_menu(self):
        """
        Run an interactive menu loop in the terminal.
        This runs AFTER rclpy.init() but BEFORE rclpy.spin() —
        because we handle service calls manually here.
        """
        print('\n' + '=' * 55)
        print('  Wall-E PID Tuner — Interactive Mode')
        print('=' * 55)
        print('  Commands:')
        print('    b <Kp> <Ki> <Kd>  → Set BALANCE PID gains')
        print('    l <Kp> <Ki> <Kd>  → Set LINE PID gains')
        print('    o <angle_deg>     → Set balance upright offset (e.g. o 10.0)')
        print('    m <0-3>           → Set mode (0=IDLE,1=BAL,2=LINE,3=BOTH)')
        print('    q                 → Quit')
        print('=' * 55)
        print('  Examples:')
        print('    b 10.0 0.0 2.5    → Balance: Kp=10, Ki=0, Kd=2.5')
        print('    o 11.5            → Set upright balance angle to 11.5 deg')
        print('    m 1               → Switch to BALANCE_ONLY mode')
        print('    m 0               → Switch to IDLE (safe to handle robot)')
        print('=' * 55 + '\n')

        while True:
            try:
                cmd = input('tuner> ').strip().lower()

                if not cmd:
                    continue

                parts = cmd.split()
                action = parts[0]

                if action == 'q':
                    print('Exiting tuner.')
                    break

                elif action == 'b' and len(parts) == 4:
                    # Balance PID: b <Kp> <Ki> <Kd>
                    self.set_pid_gains('balance', parts[1], parts[2], parts[3])

                elif action == 'l' and len(parts) == 4:
                    # Line PID: l <Kp> <Ki> <Kd>
                    self.set_pid_gains('line', parts[1], parts[2], parts[3])

                elif action == 'o' and len(parts) == 2:
                    # Offset trim: o <offset_deg>
                    self.set_pid_gains('offset', parts[1], 0.0, 0.0)

                elif action == 'm' and len(parts) == 2:
                    # Mode switch: m <0-3>
                    mode_num = int(parts[1])
                    if mode_num not in [0, 1, 2, 3]:
                        print('  Mode must be 0, 1, 2, or 3')
                    else:
                        self.set_mode(mode_num)

                else:
                    print('  Unknown command. Type "q" to quit.')

            except KeyboardInterrupt:
                print('\nExiting tuner (Ctrl+C).')
                break
            except ValueError:
                print('  Invalid number format. Example: b 40.0 0.5 2.0')
            except Exception as e:
                self.get_logger().error(f'Error: {e}')


def main(args=None):
    rclpy.init(args=args)
    node = TunerNode()

    # Wait for services before showing menu
    if node.wait_for_services():
        # Run interactive menu (blocks until user quits)
        node.interactive_menu()

    node.destroy_node()
    rclpy.shutdown()


if __name__ == '__main__':
    main()
